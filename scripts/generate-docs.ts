/**
 * Generates the Markdown reference in /docs and the catalog tables in
 * README.md from the typed catalog (src/catalog). The catalog is the single
 * source of truth, so docs cannot drift from the playground.
 *
 *   npm run docs:generate   # write files
 *   npm run docs:check      # fail if anything is out of date (CI)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import {
  catalog,
  sectionLabels,
  sectionOrder,
  type CatalogEntry,
  type Section,
} from '../src/catalog';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const docsDir = join(root, 'docs');
const checkOnly = process.argv.includes('--check');

const sectionDirs: Record<Section, string> = {
  'built-in': 'built-in-hooks',
  custom: 'custom-hooks',
  scenario: 'scenarios',
  state: 'state-management',
  esp: 'esp-js',
  testing: 'testing',
  'anti-pattern': 'anti-patterns',
};

const levelIcon = { beginner: '🟢', intermediate: '🟡', advanced: '🔴' } as const;

const entryPath = (entry: CatalogEntry) =>
  join(docsDir, sectionDirs[entry.section], `${entry.id}.md`);

/** Link from the file at `from` to an entry's generated page. */
const linkToEntry = (from: string, entry: CatalogEntry) =>
  relative(dirname(from), entryPath(entry)).split('\\').join('/');

const linkToSource = (from: string, srcRelative: string) =>
  relative(dirname(from), join(root, 'src', srcRelative))
    .split('\\')
    .join('/');

const escapeCell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** Adds GitHub's Mermaid accessibility title/description after the diagram type line. */
function accessibleMermaid(diagram: NonNullable<CatalogEntry['diagram']>): string {
  const [first = '', ...rest] = diagram.mermaid.trim().split('\n');
  const escape = (text: string) => text.replace(/[\n\r]/g, ' ');
  return [
    first,
    `    accTitle: ${escape(diagram.title)}`,
    `    accDescr: ${escape(diagram.description)}`,
    ...rest,
  ].join('\n');
}

function renderEntry(entry: CatalogEntry): string {
  const file = entryPath(entry);
  const out: string[] = [];
  const meta = [
    `${levelIcon[entry.level]} ${entry.level}`,
    `React ${entry.minReact}+`,
    `${sectionLabels[entry.section]} › ${entry.category}`,
  ];
  if (entry.support) meta.push(`support: ${entry.support.level}`);

  out.push(`<!-- Generated by scripts/generate-docs.ts from src/catalog. Do not edit by hand. -->`);
  out.push(`# ${entry.title}`, '', `> ${entry.summary}`, '', meta.join(' · '), '');
  out.push(
    `**Playground:** \`npm run dev\` → [\`#/entry/${entry.id}\`](http://localhost:5173/#/entry/${entry.id})`,
    '',
  );

  out.push('## Concept', '', entry.concept, '', '## Problem', '', entry.problem, '');

  if (entry.whenToUse?.length)
    out.push('## When to use', '', ...entry.whenToUse.map((item) => `- ${item}`), '');
  if (entry.whenNotToUse?.length) {
    out.push('## When not to use', '', ...entry.whenNotToUse.map((item) => `- ${item}`), '');
  }

  if (entry.api) {
    out.push('## API', '', '```ts', entry.api.signature, '```', '');
    if (entry.api.params?.length) {
      out.push('| Parameter | Type | Description |', '| --- | --- | --- |');
      for (const param of entry.api.params) {
        out.push(
          `| \`${escapeCell(param.name)}\`${param.optional ? ' _(optional)_' : ''} | \`${escapeCell(param.type)}\` | ${escapeCell(param.description)} |`,
        );
      }
      out.push('');
    }
    if (entry.api.returns) out.push(`**Returns:** ${entry.api.returns}`, '');
  }

  out.push('## Implementation', '');
  for (const source of entry.sources)
    out.push(`- [\`src/${source}\`](${linkToSource(file, source)})`);
  out.push('');
  if (entry.demo) {
    out.push(
      '## Interactive example',
      '',
      `- [\`src/${entry.demo}\`](${linkToSource(file, entry.demo)})`,
      '',
    );
  }

  if (entry.execution?.length) {
    out.push(
      '## Execution flow',
      '',
      ...entry.execution.map((step, index) => `${index + 1}. ${step}`),
      '',
    );
  }

  if (entry.diagram) {
    out.push(
      `## Diagram: ${entry.diagram.title}`,
      '',
      entry.diagram.description,
      '',
      '```mermaid',
      accessibleMermaid(entry.diagram),
      '```',
      '',
    );
  }

  if (entry.mistakes?.length) {
    out.push('## Common mistakes', '');
    for (const mistake of entry.mistakes) {
      out.push(
        `### ${mistake.title}`,
        '',
        '❌ Incorrect:',
        '',
        '```tsx',
        mistake.wrong,
        '```',
        '',
        mistake.why,
        '',
      );
      if (mistake.right) out.push('✅ Correct:', '', '```tsx', mistake.right, '```', '');
    }
  }

  if (entry.edgeCases?.length)
    out.push('## Edge cases', '', ...entry.edgeCases.map((item) => `- ${item}`), '');
  if (entry.support?.notes) out.push('## Browser support', '', entry.support.notes, '');

  if (entry.testing || entry.tests?.length) {
    out.push('## Testing', '');
    if (entry.testing) out.push(entry.testing, '');
    for (const test of entry.tests ?? [])
      out.push(`- [\`src/${test}\`](${linkToSource(file, test)})`);
    out.push('');
  }

  if (entry.production?.length) {
    out.push(
      '## Production considerations',
      '',
      ...entry.production.map((item) => `- ${item}`),
      '',
    );
  }

  const related = (entry.related ?? [])
    .map((id) => catalog.find((candidate) => candidate.id === id))
    .filter((item): item is CatalogEntry => !!item);
  if (related.length || entry.officialDocs?.length) {
    out.push('## Related', '');
    for (const item of related) out.push(`- [${item.title}](${linkToEntry(file, item)})`);
    for (const link of entry.officialDocs ?? [])
      out.push(`- [${link.label}](${link.url}) (official docs)`);
    out.push('');
  }

  return out.join('\n');
}

function renderTable(entries: readonly CatalogEntry[], from: string, withCategory = true): string {
  const header = withCategory
    ? ['| Topic | Category | Level | React | Summary |', '| --- | --- | --- | --- | --- |']
    : ['| Topic | Level | React | Summary |', '| --- | --- | --- | --- |'];
  const rows = entries.map((entry) => {
    const link = `[${escapeCell(entry.title)}](${linkToEntry(from, entry)})`;
    const cells = withCategory
      ? [
          link,
          escapeCell(entry.category),
          `${levelIcon[entry.level]} ${entry.level}`,
          entry.minReact,
          escapeCell(entry.summary),
        ]
      : [
          link,
          `${levelIcon[entry.level]} ${entry.level}`,
          entry.minReact,
          escapeCell(entry.summary),
        ];
    return `| ${cells.join(' | ')} |`;
  });
  return [...header, ...rows].join('\n');
}

function groupByCategory(entries: readonly CatalogEntry[]): Map<string, CatalogEntry[]> {
  const groups = new Map<string, CatalogEntry[]>();
  for (const entry of entries) {
    const list = groups.get(entry.category) ?? [];
    list.push(entry);
    groups.set(entry.category, list);
  }
  return groups;
}

function renderSectionIndex(section: Section): string {
  const file = join(docsDir, sectionDirs[section], 'README.md');
  const entries = catalog.filter((entry) => entry.section === section);
  const out = [
    `<!-- Generated by scripts/generate-docs.ts from src/catalog. Do not edit by hand. -->`,
    `# ${sectionLabels[section]}`,
    '',
    `${entries.length} topics. [Back to the documentation index](../README.md).`,
    '',
  ];
  for (const [category, list] of groupByCategory(entries)) {
    out.push(`## ${category}`, '', renderTable(list, file, false), '');
  }
  return out.join('\n');
}

function renderDocsIndex(): string {
  const out = [
    `<!-- Generated by scripts/generate-docs.ts from src/catalog. Do not edit by hand. -->`,
    '# Documentation',
    '',
    `Generated from the typed catalog in \`src/catalog\` — ${catalog.length} topics.`,
    'Each page follows the same template: concept, problem, API, implementation,',
    'interactive example, execution flow, common mistakes, edge cases, testing,',
    'production considerations and related APIs.',
    '',
    '- [Code & content conventions](CONVENTIONS.md)',
    '- [Compatibility & browser support](compatibility.md)',
    '',
  ];
  for (const section of sectionOrder) {
    const count = catalog.filter((entry) => entry.section === section).length;
    if (count === 0) continue;
    out.push(`- [${sectionLabels[section]}](${sectionDirs[section]}/README.md) — ${count} topics`);
  }
  out.push('');
  return out.join('\n');
}

function renderCompatibility(): string {
  const file = join(docsDir, 'compatibility.md');
  const byVersion = new Map<string, CatalogEntry[]>();
  for (const entry of catalog) {
    const list = byVersion.get(entry.minReact) ?? [];
    list.push(entry);
    byVersion.set(entry.minReact, list);
  }
  const versions = [...byVersion.keys()].sort(
    (a, b) => Number.parseFloat(a) - Number.parseFloat(b),
  );
  const limited = catalog.filter((entry) => entry.support && entry.support.level !== 'universal');
  const out = [
    `<!-- Generated by scripts/generate-docs.ts from src/catalog. Do not edit by hand. -->`,
    '# Compatibility & browser support',
    '',
    'The project targets **React 19.3** (`react@^19.3.1`) and **Node.js 22.12+**. Every topic',
    'records the minimum React version of the APIs it uses, so you can tell what works',
    'on older React versions.',
    '',
    '## Topics by minimum React version',
    '',
  ];
  for (const version of versions) {
    const entries = byVersion.get(version) ?? [];
    out.push(
      `### React ${version}+`,
      '',
      entries.map((entry) => `[${entry.title}](${linkToEntry(file, entry)})`).join(' · '),
      '',
    );
  }
  out.push('## Browser-dependent and client-only topics', '');
  out.push('| Topic | Support | Notes |', '| --- | --- | --- |');
  for (const entry of limited) {
    out.push(
      `| [${escapeCell(entry.title)}](${linkToEntry(file, entry)}) | ${entry.support?.level ?? ''} | ${escapeCell(entry.support?.notes ?? '')} |`,
    );
  }
  out.push('');
  return out.join('\n');
}

/** Replaces `<!-- catalog:<name>:start -->…<!-- catalog:<name>:end -->` blocks in README.md. */
function renderReadme(current: string): string {
  const file = join(root, 'README.md');
  const blocks: Record<string, string> = {
    stats: [
      `| Section | Topics |`,
      `| --- | --- |`,
      ...sectionOrder.map(
        (section) =>
          `| [${sectionLabels[section]}](docs/${sectionDirs[section]}/README.md) | ${catalog.filter((entry) => entry.section === section).length} |`,
      ),
      `| **Total** | **${catalog.length}** (${catalog.filter((entry) => entry.demo).length} with live demos) |`,
    ].join('\n'),
  };
  for (const section of sectionOrder) {
    const entries = catalog.filter((entry) => entry.section === section);
    blocks[section] = entries.length ? renderTable(entries, file) : '_No topics yet._';
  }
  let next = current;
  for (const [name, content] of Object.entries(blocks)) {
    const pattern = new RegExp(
      `(<!-- catalog:${name}:start -->)[\\s\\S]*?(<!-- catalog:${name}:end -->)`,
    );
    next = next.replace(pattern, `$1\n\n${content}\n\n$2`);
  }
  return next;
}

/**
 * Prettier's formatting of code embedded in Markdown is not always idempotent
 * (a long signature can reflow on a second pass), so format until stable —
 * otherwise `prettier --check` in CI would disagree with the generator.
 */
async function format(text: string, filepath: string): Promise<string> {
  const options = (await prettier.resolveConfig(filepath)) ?? {};
  let current = text;
  for (let pass = 0; pass < 5; pass += 1) {
    const next = await prettier.format(current, { ...options, filepath });
    if (next === current) return next;
    current = next;
  }
  return current;
}

async function main() {
  const outputs = new Map<string, string>();
  for (const entry of catalog) outputs.set(entryPath(entry), renderEntry(entry));
  for (const section of sectionOrder) {
    outputs.set(join(docsDir, sectionDirs[section], 'README.md'), renderSectionIndex(section));
  }
  outputs.set(join(docsDir, 'README.md'), renderDocsIndex());
  outputs.set(join(docsDir, 'compatibility.md'), renderCompatibility());
  const readmePath = join(root, 'README.md');
  if (existsSync(readmePath))
    outputs.set(readmePath, renderReadme(readFileSync(readmePath, 'utf8')));

  const stale: string[] = [];
  for (const [path, content] of outputs) {
    const formatted = await format(content, path);
    const existing = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (existing === formatted) continue;
    stale.push(relative(root, path));
    if (!checkOnly) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, formatted);
    }
  }

  // Generated pages whose entry no longer exists.
  for (const dir of Object.values(sectionDirs)) {
    const full = join(docsDir, dir);
    if (!existsSync(full)) continue;
    for (const name of readdirSync(full)) {
      const path = join(full, name);
      if (name.endsWith('.md') && !outputs.has(path)) {
        stale.push(`${relative(root, path)} (orphaned)`);
        if (!checkOnly) rmSync(path);
      }
    }
  }

  if (checkOnly && stale.length) {
    console.error(
      `Docs are out of date. Run \`npm run docs:generate\`.\n${stale.map((item) => `  - ${item}`).join('\n')}`,
    );
    process.exit(1);
  }
  console.log(
    checkOnly
      ? 'Docs are up to date.'
      : `Wrote ${stale.length} file(s); ${outputs.size} generated in total.`,
  );
}

await main();
